//
// Layout: BADGE_FONT_COLS[ch - 0x20][column], bit r of a column byte = pixel at row r, row 0 at the
// cap line and row 7 on the baseline. BADGE_FONT_ADVANCE is the pen movement in pixels including a
// one-pixel gap, so text is drawn proportionally and stays legible across 320 px.
